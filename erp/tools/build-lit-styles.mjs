import { readdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import * as sass from 'sass';

const repoRoot = join(dirname(fileURLToPath(import.meta.url)), '..');
const roots = [
  join(repoRoot, 'packages/vector-widgets/src'),
  join(repoRoot, 'apps/operations/src/app/features'),
];

const styleFiles = (
  await Promise.all(roots.map((root) => findStyleFiles(root)))
).flat();

for (const sourcePath of styleFiles) {
  const result = await sass.compileAsync(sourcePath, {
    loadPaths: [dirname(sourcePath)],
    style: 'expanded',
  });
  const exportName = exportNameFor(sourcePath);
  const outputPath = sourcePath.replace(
    /\.styles\.scss$/,
    '.styles.generated.ts',
  );
  const cssText = result.css
    .replaceAll('\\', '\\\\')
    .replaceAll('`', '\\`')
    .replaceAll('${', '\\${');
  const output =
    '// Generated by tools/build-lit-styles.mjs. Do not edit.\n' +
    "import { css } from 'lit';\n\n" +
    `export const ${exportName} = css\`${cssText}\`;\n`;
  const previous = await readFile(outputPath, 'utf8').catch(() => '');
  if (previous !== output) await writeFile(outputPath, output, 'utf8');
  console.log(
    `${relative(repoRoot, sourcePath)} -> ${relative(repoRoot, outputPath)}`,
  );
}

async function findStyleFiles(root) {
  const entries = await readdir(root, { withFileTypes: true });
  const files = await Promise.all(
    entries.map((entry) => {
      const path = join(root, entry.name);
      if (entry.isDirectory()) return findStyleFiles(path);
      return entry.name.endsWith('.styles.scss') ? [path] : [];
    }),
  );
  return files.flat();
}

function exportNameFor(path) {
  const fileName = path
    .split(/[\\/]/)
    .at(-1)
    .replace(/\.styles\.scss$/, '');
  return `${fileName.replace(/-([a-z])/g, (_, letter) => letter.toUpperCase())}Styles`;
}
